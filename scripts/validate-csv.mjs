function distKm(a, b) {
  const R = 6371;
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(b[0] - a[0]);
  const dLng = toRad(b[1] - a[1]);
  const s =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a[0])) * Math.cos(toRad(b[0])) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

const text = fs.readFileSync(CSV, "utf8");
const { data } = Papa.parse(text, { header: true, skipEmptyLines: true });

const bad = [];
const unmatched = [];
for (const row of data) {
  const addr = row["住所"];
  const lat = parseFloat(row["緯度"]);
  const lng = parseFloat(row["経度"]);
  const city = CITIES.find((c) => c.m.test(addr));
  if (!city) {
    unmatched.push(row);
    continue;
  }
  const d = distKm([lat, lng], city.c);
  if (d > city.r) {
    bad.push({ ...row, dist: d.toFixed(2), expected: city.r, city: city.m.source });
  }
}
console.log(`🔍 ${data.length} 件チェック`);
console.log(`❌ 明らかに異常: ${bad.length} 件`);
for (const b of bad) {
  console.log(
    `  ${b["店舗名"]} / ${b["住所"]} → (${b["緯度"]}, ${b["経度"]})  ${b.dist}km ズレ (許容 ${b.expected}km / ${b.city})`
  );
}
if (unmatched.length) {
  console.log(`\n⚠️  市区町村パターン未マッチ: ${unmatched.length} 件`);
  for (const u of unmatched) console.log(`  ${u["店舗名"]} / ${u["住所"]}`);
}
